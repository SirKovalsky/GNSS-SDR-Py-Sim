"""BeiDou B1I D1 navigation message construction (BDS-SIS-ICD-2.0/2.1).

This module builds a standards-shaped B1I D1 bit stream from the BeiDou
ephemeris already parsed into :class:`gnss_sim.rinex.Ephemeris` so that a real
receiver can acquire the B1I code, synchronise on the 20-chip Neumann-Hoffman
(NH) secondary code, de-interleave, BCH-decode and finally compute a
position/clock solution.

Verified structure (cross-checked against two independent sources)
-------------------------------------------------------------------
.. [1] BDS-SIS-ICD-2.0/-2.1 (section 5.1.3 and 5.2.2).  Channel rate 50 bps,
   NH code ``00000100110101001110`` at 1 kbps (20 ms = one data bit), BCH
   ``g(X) = X**4 + X + 1`` (BCH(15,11,1)) plus a 30-bit block interleaver.
   Frame = 1500 bits / 30 s = 5 subframes; subframe = 300 bits / 6 s = 10
   words; word = 30 bits.  Word 1: 15 raw bits + one BCH block (26 info bits);
   words 2..10: two BCH blocks + interleaving (22 info bits each).
.. [2] Field bit positions/scale factors taken from GNSS-SDRLIB
   (``sdrnav_bds.c``, Taro Suzuki) and GNSS-SDR (``Beidou_DNAV.h``).  Both
   agree on every field used here (``toe``/``toc``, the Keplerian elements and
   the clock polynomial).  The two disagree on the number of bits read for
   ``TGD2`` (10 vs 6); TGD/ionosphere/UTC/almanac are **not** required for a
   position fix, so they are broadcast as zero rather than risking a wrong
   value.

Caveats (marked, not silently wrong)
------------------------------------
* The D1 field ordering/scale factors are taken from the two open-source
  decoders above; they were **not** verified against a live broadcast capture
  in this project.  :func:`self_test` verifies BCH, interleaving and a full
  subframe round-trip (build -> decode -> compare) but that only proves the
  encoder/decoder pair is self-consistent.
* ``TGD1/TGD2``, the BDS ionosphere ``alpha/beta`` and the UTC parameters are
  transmitted as zero (marked TODO).  They bias the clock by a few ns and do
  not prevent a first fix.
* The broadcast ``SOW`` follows the simulator's own time scale so that the
  receiver's ``t_k`` matches the geometry generated by
  :mod:`gnss_sim.engine` (see :func:`d1_frame_block`).

Bit polarity: the engine maps ``bit -> 1 - 2*bit`` (0 -> +1), consistent with
the other signals in this project; a receiver resolves the carrier phase.
"""

