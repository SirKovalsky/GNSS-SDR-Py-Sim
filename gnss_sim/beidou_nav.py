BCH_N = 15
BCH_K = 11
BCH_PARITY = 4
#: g(X) = X**4 + X + 1 -> 0b10011
BCH_POLY = 0b10011

#: BDT reference constants (BDT = GPST - 14 s; BDT week = GPS week - 1356).
BDT_GPST_OFFSET_S = 14.0
BDT_WEEK_OFFSET = 1356


# ----------------------------------------------------------------------
# BCH(15,11,1) with g(X) = X**4 + X + 1
# ----------------------------------------------------------------------
def _poly_rem(bits: Sequence[int]) -> int:
    """Remainder of the polynomial ``bits`` (MSB first) divided by ``g(X)``."""
    reg = 0
    for b in bits:
        reg = (reg << 1) | (int(b) & 1)
        if reg & (1 << BCH_PARITY):        # degree >= 4
            reg ^= BCH_POLY
    return reg & 0xF


def bch_encode(info_bits: Sequence[int]) -> list[int]:
    """Systematic BCH(15,11,1) encode: 11 information + 4 parity bits."""
    info = [int(b) & 1 for b in info_bits]
    if len(info) != BCH_K:
        raise ValueError(f"BCH info must be {BCH_K} bits")
    reg = _poly_rem(info + [0] * BCH_PARITY)   # remainder of info(X)*X**4
    return info + [(reg >> (3 - i)) & 1 for i in range(BCH_PARITY)]


def _synonym_table() -> dict[int, int]:
    """Map a nonzero syndrome to the (0-based) bit position to flip.

    ``BCH(15,11)`` with a primitive generator is a Hamming code: each of the
    15 single-bit errors has a distinct syndrome.
    """
    def mul_x(r: int) -> int:
        r <<= 1
        if r & 0x10:
            r ^= BCH_POLY
        return r & 0xF

    table: dict[int, int] = {}
    rem = 1
    for exp in range(15):                  # rem = X**exp mod g(X)
        pos = 14 - exp                     # bit p has coefficient X**(14-p)
        table[rem] = pos
        rem = mul_x(rem)
    return table


_SYNDROME = _synonym_table()


def bch_decode(codeword: Sequence[int]) -> tuple[list[int], bool]:
    """Correct one bit of a 15-bit BCH codeword.

    Returns ``(corrected_bits, corrected)``; ``codeword`` is returned as a
    15-bit list (11 information + 4 parity) with the parity still appended.
    """
    cw = [int(b) & 1 for b in codeword]
    if len(cw) != BCH_N:
        raise ValueError(f"BCH codeword must be {BCH_N} bits")
    reg = _poly_rem(cw)
    if reg == 0:
        return cw, False
    pos = _SYNDROME.get(reg)
    if pos is None:                        # pragma: no cover - unreachable
        return cw, False
    cw[pos] ^= 1
    return cw, True


# ----------------------------------------------------------------------
# Interleaving of two 15-bit codewords into a 30-bit word
# ----------------------------------------------------------------------
def interleave(codeword1: Sequence[int], codeword2: Sequence[int]) -> list[int]:
    """Parallel/serial interleave: ``c1[0] c2[0] c1[1] c2[1] ...``."""
    c1 = [int(b) & 1 for b in codeword1]
    c2 = [int(b) & 1 for b in codeword2]
    if len(c1) != BCH_N or len(c2) != BCH_N:
        raise ValueError("each BCH codeword must be 15 bits")
    out: list[int] = []
    for i in range(BCH_N):
        out.append(c1[i])
        out.append(c2[i])
    return out


def deinterleave(word: Sequence[int]) -> tuple[list[int], list[int]]:
    """Inverse of :func:`interleave` (two 15-bit codewords)."""
    w = [int(b) & 1 for b in word]
    if len(w) != WORD_BITS:
        raise ValueError("word must be 30 bits")
    c1 = [w[2 * i] for i in range(BCH_N)]
    c2 = [w[2 * i + 1] for i in range(BCH_N)]
    return c1, c2


def encode_word(x1: Sequence[int], x2: Sequence[int]) -> list[int]:
    """Encode two 11-bit information blocks into a transmitted 30-bit word."""
    return interleave(bch_encode(x1), bch_encode(x2))


def decode_word(word: Sequence[int]) -> tuple[list[int], list[int]]:
    """Decode a transmitted word into ``(info22, parity8)``.

    ``info22`` is ``X1(11) + X2(11)`` and ``parity8`` is ``P1(4) + P2(4)``,
    i.e. the logical ("decoded") word layout used by the field positions.
    """
    c1, c2 = deinterleave(word)
    d1, _ = bch_decode(c1)
    d2, _ = bch_decode(c2)
    return d1[:BCH_K] + d2[:BCH_K], d1[BCH_K:] + d2[BCH_K:]


# ----------------------------------------------------------------------
# small bit helpers
# ----------------------------------------------------------------------
def _scale(value: float, lsb: float, width: int, signed: bool) -> int:
    raw = int(round(float(value) / lsb)) if lsb else int(round(float(value)))
    if signed:
        lo, hi = -(1 << (width - 1)), (1 << (width - 1)) - 1
    else:
        lo, hi = 0, (1 << width) - 1
    return max(lo, min(hi, raw))


def _put_parts(bits: list[int], parts: Sequence[tuple[int, int]],
               value: float, lsb: float = 1.0, signed: bool = False) -> None:
    """Write ``value`` MSB-first across the concatenated ``parts``."""
    width = sum(w for _pos, w in parts)
    raw = _scale(value, lsb, width, signed) & ((1 << width) - 1)
    chunk = [(raw >> (width - 1 - i)) & 1 for i in range(width)]
    k = 0
    for pos, w in parts:
        for j in range(w):
            bits[pos + j] = chunk[k]
            k += 1


def _put_raw_parts(bits: list[int], parts: Sequence[tuple[int, int]],
                   value: int, width: int | None = None) -> None:
    total = sum(w for _pos, w in parts)
    if width is None:
        width = total
    raw = int(value) & ((1 << width) - 1)
    chunk = [(raw >> (width - 1 - i)) & 1 for i in range(width)]
    k = 0
    for pos, w in parts:
        for j in range(w):
            bits[pos + j] = chunk[k]
            k += 1


def _read_parts(bits: Sequence[int], parts: Sequence[tuple[int, int]],
                signed: bool = False) -> int:
    width = sum(w for _pos, w in parts)
    value = 0
    for pos, w in parts:
        for j in range(w):
            value = (value << 1) | (int(bits[pos + j]) & 1)
    if signed and (value >> (width - 1)) & 1:
        value -= 1 << width
    return value


